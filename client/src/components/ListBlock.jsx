import React from 'react';

export default function ListBlock({ data, onUpdate }) {

  let listTitle;
  switch (data.style) {
    case 'lettered':
      listTitle = 'Буквенный список';
      break;
    case 'numbered':
      listTitle = 'Нумерованный список';
      break;
    default:
      listTitle = 'Маркированный список';
  }
  // --- Функции для управления элементами больше не нужны, так как мы используем одно текстовое поле ---

  return (
    <div>
      {/* Статичная метка, показывающая тип блока, как на макете */}
      <div className="block-label">{listTitle}</div>
      
      {/* 
        Одно большое текстовое поле для редактирования всех пунктов.
        Это гораздо удобнее для пользователя (можно копировать/вставлять, легко добавлять новые строки).
      */}


      
      <textarea
        // 1. Превращаем массив пунктов ['Пункт 1', 'Пункт 2'] в одну строку с переносами "Пункт 1\nПункт 2"
        value={data.items.join('\n')}
        
        // 2. При изменении текста делаем обратную операцию:
        //    Берем строку "Пункт 1\nПункт 2" и превращаем ее обратно в массив ['Пункт 1', 'Пункт 2']
        onChange={(e) => onUpdate({ ...data, items: e.target.value.split('\n') })}
        
        placeholder="Введите пункты списка, каждый с новой строки"
        className="block-textarea" // Используем тот же стиль, что и у параграфа
        
        // 3. Автоматически подстраиваем высоту поля под количество пунктов
        rows={data.items.length + 1} 
      />
    </div>
  );
}